func genLazyVimPlugin(rootDir string, s spec.GrammarSpec) {
	var kwList []string
	for _, k := range s.Keywords {
		kwList = append(kwList, k.Name)
	}
	var typeList []string
	for _, t := range s.Types {
		typeList = append(typeList, t.Name)
	}
	var builtinList []string
	for _, b := range s.Builtins {
		builtinList = append(builtinList, b.Name)
	}

	var cmpItems []string
	for _, k := range s.Keywords {
		cmpItems = append(cmpItems, fmt.Sprintf("{ label = %q, kind = 14, detail = %q }", k.Name, k.Description))
	}
	for _, t := range s.Types {
		cmpItems = append(cmpItems, fmt.Sprintf("{ label = %q, kind = 7, detail = %q }", t.Name, t.Description))
	}
	for _, b := range s.Builtins {
		cmpItems = append(cmpItems, fmt.Sprintf("{ label = %q, kind = 3, detail = %q }", b.Name, b.Description))
	}

	content := fmt.Sprintf(`-- LazyVim Plugin Specification for Gatwd
-- Copy or symlink this file directly into:
-- ~/.config/nvim/lua/plugins/gatwd.lua
-- Auto-generated by cmd/gatwd-gen - DO NOT EDIT MANUALLY.

return {
  -- 1. Register Gatwd Filetype & Comment Syntax
  {
    "nvim-treesitter/nvim-treesitter",
    opts = function(_, opts)
      vim.filetype.add({
        extension = {
          gatwd = "gatwd",
        },
      })
    end,
  },

  -- 2. Syntax Highlighting Definition
  {
    "LazyVim/LazyVim",
    opts = function()
      vim.api.nvim_create_autocmd("FileType", {
        pattern = "gatwd",
        callback = function()
          vim.bo.commentstring = "-- %%s"
          vim.cmd([[
            syntax keyword gatwdKeyword %s
            syntax keyword gatwdType %s
            syntax keyword gatwdBuiltin %s
            syntax match gatwdPipe /|>\|||>\|⊳/
            syntax match gatwdArrow /->\|<-\|→/
            syntax match gatwdArrowCombinator /&&&\|\*\*\*/
            syntax match gatwdOperator /==\|!=\|<=\|>=\|&&\|||\|++\|\/\/\|[+\-*/%%<>]/
            syntax match gatwdComment /--.*$/
            syntax region gatwdString start=/"/ skip=/\\"/ end=/"/
            syntax match gatwdNumber /\v<[0-9]+(\.[0-9]+)?(i)?>/

            highlight default link gatwdKeyword Keyword
            highlight default link gatwdType Type
            highlight default link gatwdBuiltin Function
            highlight default link gatwdPipe Special
            highlight default link gatwdArrow Operator
            highlight default link gatwdArrowCombinator Operator
            highlight default link gatwdOperator Operator
            highlight default link gatwdComment Comment
            highlight default link gatwdString String
            highlight default link gatwdNumber Number
          ]])
        end,
      })
    end,
  },

  -- 3. nvim-cmp Auto-completion for Keywords, Types, and Builtins
  {
    "hrsh7th/nvim-cmp",
    optional = true,
    opts = function(_, opts)
      local cmp = require("cmp")
      local gatwd_source = {
        complete = function(self, params, callback)
          if vim.bo.filetype ~= "gatwd" then
            return callback({ items = {}, isIncomplete = false })
          end
          local items = {
            %s
          }
          callback({ items = items, isIncomplete = false })
        end,
      }
      cmp.register_source("gatwd", gatwd_source)
      opts.sources = opts.sources or {}
      table.insert(opts.sources, { name = "gatwd", priority = 100 })
    end,
  },

  -- 4. nvim-lint Diagnostics via gatwd --check
  {
    "mfussenegger/nvim-lint",
    optional = true,
    opts = function(_, opts)
      local lint = require("lint")
      local bin = vim.fn.expand("~/go/bin/gatwd")
      if vim.fn.executable("gatwd") == 1 then
        bin = "gatwd"
      end

      lint.linters.gatwd = {
        name = "gatwd",
        cmd = bin,
        stdin = false,
        args = { "--check" },
        ignore_exitcode = true,
        stream = "stderr",
        parser = require("lint.parser").from_errorformat("%%f:%%l:%%c: %%trror: %%m", {
          source = "gatwd",
          severity = vim.diagnostic.severity.ERROR,
        }),
      }

      opts.linters_by_ft = opts.linters_by_ft or {}
      opts.linters_by_ft.gatwd = { "gatwd" }
    end,
  },
}
`, strings.Join(kwList, " "), strings.Join(typeList, " "), strings.Join(builtinList, " "), strings.Join(cmpItems, ",\n            "))

	mustWrite(filepath.Join(rootDir, "editors/neovim/lua/plugins/gatwd.lua"), content)
}

func genSnippets(rootDir string, s spec.GrammarSpec) {
	snippetsMap := make(map[string]map[string]any)
	for _, snip := range s.Snippets {
		bodyLines := strings.Split(snip.Body, "\n")
		snippetsMap[snip.Description] = map[string]any{
			"prefix":      snip.Prefix,
			"body":        bodyLines,
			"description": snip.Description,
		}
	}
	bytes, _ := json.MarshalIndent(snippetsMap, "", "  ")
	mustWrite(filepath.Join(rootDir, "editors/neovim/snippets/gatwd.json"), string(bytes)+"\n")
}

