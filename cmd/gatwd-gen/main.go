func genTreeSitter(rootDir string, s spec.GrammarSpec) {
	content := fmt.Sprintf(`// Tree-sitter grammar definition for Gatwd DSL
// Auto-generated by cmd/gatwd-gen - DO NOT EDIT MANUALLY.

module.exports = grammar({
  name: '%s',

  extras: $ => [
    /\s/,
    $.comment,
  ],

  rules: {
    source_file: $ => repeat($._statement),

    _statement: $ => choice(
      $.import_statement,
      $.type_definition,
      $.const_definition,
      $.function_definition,
      $.let_binding,
      $.pipeline,
    ),

    comment: $ => token(seq('--', /.*/)),

    import_statement: $ => seq('import', $.string),

    type_definition: $ => seq('type', $.identifier, '=', $._type_expr),

    const_definition: $ => seq('const', $.identifier, '=', $._expression),

    function_definition: $ => seq('def', $.identifier, '=', $._expression),

    let_binding: $ => seq('let', $.identifier, '=', $._expression, 'in', $._expression),

    pipeline: $ => prec.left(seq(
      $._expression,
      repeat1(seq(choice('|>', '||>', '⊳'), $._expression)),
    )),

    _expression: $ => choice(
      $.identifier,
      $.number,
      $.string,
      $.list_comprehension,
      $.match_expression,
      $.seq_expression,
      $.binary_expression,
    ),

    list_comprehension: $ => seq('[', $._expression, '|', $.identifier, '<-', $._expression, ']'),

    match_expression: $ => seq('match', '{', repeat($.match_arm), '}'),

    match_arm: $ => seq(optional('|'), $._pattern, '->', $._expression),

    _pattern: $ => choice(
      $.identifier,
      $.number,
      $.list_pattern,
      '_',
    ),

    list_pattern: $ => seq('[', commaSep($._pattern), optional(seq(', ...', $.identifier)), ']'),

    seq_expression: $ => seq('seq', '{', repeat($._expression), '}'),

    binary_expression: $ => prec.left(seq(
      $._expression,
      choice('+', '-', '*', '/', '//', '%%', '++', '==', '!=', '<', '<=', '>', '>=', '&&', '||'),
      $._expression,
    )),

    identifier: $ => /[a-zA-Z_][a-zA-Z0-9_]*/,
    number: $ => /[0-9]+(\.[0-9]+)?(i)?/,
    string: $ => seq('"', repeat(/[^"\\]/), '"'),
  },
});

function commaSep(rule) {
  return optional(seq(rule, repeat(seq(',', rule))));
}
`, s.FileExtension)

	mustWrite(filepath.Join(rootDir, "editors/treesitter/grammar.js"), content)
}

func genGoTokens(rootDir string, s spec.GrammarSpec) {
	var kwEntries []string
	for _, k := range s.Keywords {
		kwEntries = append(kwEntries, fmt.Sprintf("\t%q: %q,", k.Name, k.Description))
	}
	var typeEntries []string
	for _, t := range s.Types {
		typeEntries = append(typeEntries, fmt.Sprintf("\t%q: %q,", t.Name, t.Description))
	}
	var builtinEntries []string
	for _, b := range s.Builtins {
		builtinEntries = append(builtinEntries, fmt.Sprintf("\t%q: {Category: %q, Signature: %q, Description: %q},", b.Name, b.Category, b.Signature, b.Description))
	}
	var opEntries []string
	for _, o := range s.Operators {
		opEntries = append(opEntries, fmt.Sprintf("\t%q: {Category: %q, Precedence: %d, Associativity: %q, Description: %q, Unicode: %q},", o.Symbol, o.Category, o.Precedence, o.Associativity, o.Description, o.Unicode))
	}

	content := fmt.Sprintf(`package parser

// Code generated by cmd/gatwd-gen. DO NOT EDIT.

type BuiltinMetadata struct {
	Category    string
	Signature   string
	Description string
}

type OperatorMetadata struct {
	Category      string
	Precedence    int
	Associativity string
	Description   string
	Unicode       string
}

// CanonicalKeywords contains all official Gatwd keywords.
var CanonicalKeywords = map[string]string{
%s
}

// CanonicalTypes contains all built-in types and ADT constructors.
var CanonicalTypes = map[string]string{
%s
}

// CanonicalBuiltins contains all built-in transducers, optics, and adapters.
var CanonicalBuiltins = map[string]BuiltinMetadata{
%s
}

// CanonicalOperators contains all operators, pipes, and arrows.
var CanonicalOperators = map[string]OperatorMetadata{
%s
}
`, strings.Join(kwEntries, "\n"), strings.Join(typeEntries, "\n"), strings.Join(builtinEntries, "\n"), strings.Join(opEntries, "\n"))

	mustWrite(filepath.Join(rootDir, "parser/tokens_gen.go"), content)
}
