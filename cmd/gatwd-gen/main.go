package main

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/joergreinhardt/gatwd/spec"
)

func main() {
	s := spec.DefaultSpec()
	rootDir := "."
	if len(os.Args) > 1 {
		rootDir = os.Args[1]
	}

	fmt.Println("=== Gatwd Pipeline Code Generator ===")
	fmt.Printf("Generating editor configurations, grammars, and Go constants from spec...\n")

	// 1. Generate editors/neovim/syntax/gatwd.vim
	genVimSyntax(rootDir, s)

	// 2. Generate editors/neovim/ftdetect/gatwd.lua
	genVimFtDetect(rootDir, s)

	// 3. Generate editors/neovim/lua/plugins/gatwd.lua (LazyVim plugin)
	genLazyVimPlugin(rootDir, s)

	// 4. Generate editors/neovim/snippets/gatwd.json (LuaSnip / VS Code snippets)
	genSnippets(rootDir, s)

	// 5. Generate editors/vscode/syntaxes/gatwd.tmLanguage.json (TextMate)
	genTextMate(rootDir, s)

	// 6. Generate editors/treesitter/grammar.js (Tree-sitter)
	genTreeSitter(rootDir, s)

	// 7. Generate parser/tokens_gen.go (Go symbol tables)
	genGoTokens(rootDir, s)

	fmt.Println("✅ Generation complete! All editor plugins, grammars, and symbol tables are in sync.")
}

func mustWrite(path string, content string) {
	dir := filepath.Dir(path)
	if err := os.MkdirAll(dir, 0755); err != nil {
		fmt.Fprintf(os.Stderr, "Error creating directory %s: %v\n", dir, err)
		os.Exit(1)
	}
	if err := os.WriteFile(path, []byte(content), 0644); err != nil {
		fmt.Fprintf(os.Stderr, "Error writing file %s: %v\n", path, err)
		os.Exit(1)
	}
	fmt.Printf("  -> Generated: %s\n", path)
}

func genVimSyntax(rootDir string, s spec.GrammarSpec) {
	var kwList []string
	for _, k := range s.Keywords {
		kwList = append(kwList, k.Name)
	}
	var typeList []string
	for _, t := range s.Types {
		typeList = append(typeList, t.Name)
	}
	var builtinList []string
	for _, b := range s.Builtins {
		builtinList = append(builtinList, b.Name)
	}

	content := fmt.Sprintf(`" Vim syntax file for Gatwd DSL
" Auto-generated by cmd/gatwd-gen - DO NOT EDIT MANUALLY.

if exists("b:current_syntax")
  finish
endif

" Keywords
syntax keyword gatwdKeyword %s

" Types
syntax keyword gatwdType %s

" Built-in Transducers & Optics
syntax keyword gatwdBuiltin %s

" Pipes, Arrows, and Combinators
syntax match gatwdPipe /|>\|||>\|⊳/
syntax match gatwdArrow /->\|<-\|→/
syntax match gatwdArrowCombinator /&&&\|\*\*\*/

" Infix Math & Logic
syntax match gatwdOperator /==\|!=\|<=\|>=\|&&\|||\|++\|\/\/\|[+\-*/%%<>]/

" Comments
syntax match gatwdComment /--.*$/

" Strings
syntax region gatwdString start=/"/ skip=/\\"/ end=/"/

" Numbers
syntax match gatwdNumber /\v<[0-9]+(\.[0-9]+)?(i)?>/

" Highlighting Links
highlight default link gatwdKeyword Keyword
highlight default link gatwdType Type
highlight default link gatwdBuiltin Function
highlight default link gatwdPipe Special
highlight default link gatwdArrow Operator
highlight default link gatwdArrowCombinator Operator
highlight default link gatwdOperator Operator
highlight default link gatwdComment Comment
highlight default link gatwdString String
highlight default link gatwdNumber Number

let b:current_syntax = "gatwd"
`, strings.Join(kwList, " "), strings.Join(typeList, " "), strings.Join(builtinList, " "))

	mustWrite(filepath.Join(rootDir, "editors/neovim/syntax/gatwd.vim"), content)
}

